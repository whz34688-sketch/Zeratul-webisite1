import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const currentDir = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.resolve(currentDir, "..");
const sourcePath = path.join(projectRoot, "knowledge", "Zeratul个人信息库.md");
const targetPath = path.join(projectRoot, "server", "chat", "knowledge-source.js");

const markdown = await readFile(sourcePath, "utf8");
const output = `// Auto-generated by scripts/sync-knowledge.mjs.\n// Source of truth: knowledge/Zeratul个人信息库.md\nexport default ${JSON.stringify(markdown)};\n`;

await mkdir(path.dirname(targetPath), { recursive: true });
await writeFile(targetPath, output, "utf8");

console.log(`Synced knowledge base to ${path.relative(projectRoot, targetPath)}`);
